// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every rankable pre-token protocol in the snapshot: every slug on the watchlist (the
// floor, never a ceiling) plus every other pre-token protocol outside the watchlist that passes the
// board's exclusion rule — not an exchange, not a wrapped, staked or bridged product of a protocol
// whose token already trades, not a versioned pool — below the floor and above it alike. A protocol
// is pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   scale      = 0.25 x tvl_usd^0.75 x tvl_max^0.25   (tvl_max: the largest TVL in the snapshot)
//   growth     = clamp(change_7d, -60, 150) per cent
//   growthMult = 1 + (growth / 100) x 0.75
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied    = max(1, round(scale x growthMult x maturity))
//
// The scale is log-compressed on purpose: at tvl_max it equals 0.25 x tvl_max exactly, as a flat
// multiple would, but smaller protocols are lifted toward it, so growth and age can move their rank.
//
// The constants are the house model's, stated in the dashboard and changeable in the model sandbox. No
// protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}


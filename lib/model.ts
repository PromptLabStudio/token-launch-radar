/** Chains where a transaction costs well under a dollar, so a farm plan can afford many small moves. */
const LOW_FEE_CHAINS = new Set(['Arbitrum', 'Base', 'Optimism', 'zkSync', 'Polygon', 'Linea', 'Scroll', 'Blast', 'Mantle', 'Mode', 'Starknet', 'Solana', 'Avalanche', 'Binance', 'Tron', 'Hyperliquid L1']);

/** The gas figures a plan states, from the protocol's own chains: mainnet-only plans cost real money. */
function gasFor(p: SnapshotProtocol): { gas: string; weekly: string; where: string } {
  const lowFee = p.chains.find((c) => LOW_FEE_CHAINS.has(c));
  const mainnetHeavy = p.chains.length > 0 && p.chains[0] === 'Ethereum' && lowFee === undefined;
  if (mainnetHeavy) return { gas: 'about $5 to $15 of gas per transaction on Ethereum mainnet', weekly: 'about $5 to $15 of gas a week', where: 'Ethereum mainnet' };
  return { gas: 'under $1 of gas per transaction on a low-fee chain', weekly: 'under $1 of gas a week', where: lowFee ?? chainOf(p) };
}

/**
 * A protocol's farm plan: eight steps, each an action with a cost and a time. The plan is derived from
 * the protocol's own record (category, chains, TVL, age), never from a hand-written list of names.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  const gas = gasFor(p);
  const action = actionFor(p, capital, chain);
  return [
    {
      text: `Use a fresh wallet that holds only the funds you plan to farm, and keep its seed phrase offline.`,
      cost: 'under $3 of gas for the first transaction',
      time: '5 minutes',
    },
    {
      text: `Check the gas cost on ${gas.where} before you start: ${gas.gas}.`,
      cost: gas.gas,
      time: '5 minutes',
    },
    {
      text: action,
      cost: `$${capital} of capital and about $${capital >= 150 ? 8 : 4} of gas`,
      time: '15 minutes to set up',
    },
    {
      text: `Make one qualifying action each week, such as a deposit, a borrow, a swap or a vote.`,
      cost: gas.weekly,
      time: '10 minutes a week',
    },
    {
      text: `Hold the position for at least ${hold} days so the activity is counted in more than one snapshot.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Open the protocol's own points or rewards page and check the eligibility rules — which actions count, the minimum hold, and the snapshot dates — before you change anything.`,
      cost: 'no fee to check, and never pay to claim',
      time: '10 minutes',
    },
    {
      text: `Before you withdraw, open the protocol's own points or rewards page and claim only from the link it publishes.`,
      cost: 'no fee to claim from the official link',
      time: '10 minutes',
    },
    {
      text: `Write the wallet, the dates and every transaction in a farm log so you can repeat the position or unwind it.`,
      cost: 'nothing but the log',
      time: '5 minutes',
    },
  ];
}

/** The live-token protocols, by market cap, for the dashboard's Live token view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => !isPreToken(p) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
    }));
}

